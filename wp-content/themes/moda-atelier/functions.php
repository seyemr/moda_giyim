/**
 * Remember accounts whose password was generated by the site and never seen by the customer.
 *
 * @param int   $customer_id        User ID.
 * @param array $new_customer_data  Customer data.
 * @param bool  $password_generated Whether the password was generated.
 * @return void
 */
function moda_atelier_flag_generated_password( $customer_id, $new_customer_data = array(), $password_generated = false ) {
	if ( $password_generated ) {
		update_user_meta( $customer_id, 'moda_password_generated', '1' );
	}
}
add_action( 'woocommerce_created_customer', 'moda_atelier_flag_generated_password', 10, 3 );

/**
 * Whether the user still has an unseen, site-generated password.
 *
 * @param int $user_id User ID.
 * @return bool
 */
function moda_atelier_has_generated_password( $user_id ) {
	return $user_id > 0 && '1' === get_user_meta( $user_id, 'moda_password_generated', true );
}

/**
 * Let a signed-in customer with a generated password choose a new one without the current password.
 *
 * The request still needs a valid session and the WooCommerce account-form nonce.
 *
 * @return void
 */
function moda_atelier_allow_first_password_change() {
	$user_id = get_current_user_id();
	if ( ! moda_atelier_has_generated_password( $user_id ) || 'POST' !== ( $_SERVER['REQUEST_METHOD'] ?? '' ) ) {
		return;
	}

	$action = isset( $_POST['action'] ) ? sanitize_text_field( wp_unslash( $_POST['action'] ) ) : '';
	$nonce  = isset( $_POST['save-account-details-nonce'] ) ? sanitize_text_field( wp_unslash( $_POST['save-account-details-nonce'] ) ) : '';
	if ( 'save_account_details' !== $action || ! wp_verify_nonce( $nonce, 'save_account_details' ) || empty( $_POST['password_1'] ) ) {
		return;
	}

	$placeholder              = wp_generate_password( 32, false );
	$_POST['password_current'] = $placeholder;
	add_filter(
		'check_password',
		static function ( $check, $password, $hash, $checked_user_id ) use ( $placeholder, $user_id ) {
			return ( (int) $checked_user_id === $user_id && hash_equals( $placeholder, (string) $password ) ) ? true : $check;
		},
		10,
		4
	);
}
add_action( 'wp_loaded', 'moda_atelier_allow_first_password_change', 5 );

/**
 * Forget the generated-password flag once the customer sets a password.
 *
 * @param int $user_id User ID.
 * @return void
 */
function moda_atelier_clear_generated_password_flag( $user_id ) {
	if ( ! empty( $_POST['password_1'] ) ) { // phpcs:ignore WordPress.Security.NonceVerification.Missing -- Runs after WooCommerce verified the nonce.
		delete_user_meta( $user_id, 'moda_password_generated' );
	}
}
add_action( 'woocommerce_save_account_details', 'moda_atelier_clear_generated_password_flag' );

/**
 * Clear the flag after a password reset.
 *
 * @param WP_User $user User object.
 * @return void
 */
function moda_atelier_clear_generated_password_flag_on_reset( $user ) {
	delete_user_meta( $user->ID, 'moda_password_generated' );
}
add_action( 'after_password_reset', 'moda_atelier_clear_generated_password_flag_on_reset' );

/**
 * Explain the first-password step and hide the current-password field.
 *
 * @return void
 */
function moda_atelier_first_password_notice() {
	if ( ! moda_atelier_has_generated_password( get_current_user_id() ) ) {
		return;
	}
	echo '<style>.woocommerce-EditAccountForm .woocommerce-form-row:has(#password_current),.woocommerce-EditAccountForm p:has(#password_current){display:none}</style>';
	echo '<p class="ma-notice">' . esc_html__( 'Hesabınız için size ilk şifre otomatik oluşturuldu. Aşağıdan kendi şifrenizi belirlemeniz yeterli; eski şifre gerekmez.', 'moda-atelier' ) . '</p>';
}
add_action( 'woocommerce_edit_account_form_start', 'moda_atelier_first_password_notice' );

/**
 * Send new customers to the account details page to choose their password.
 *
 * @param string $redirect Redirect URL.
 * @return string
 */
function moda_atelier_registration_redirect( $redirect ) {
	if ( function_exists( 'wc_get_endpoint_url' ) && function_exists( 'wc_get_page_permalink' ) ) {
		return wc_get_endpoint_url( 'edit-account', '', wc_get_page_permalink( 'myaccount' ) );
	}
	return $redirect;
}
add_filter( 'woocommerce_registration_redirect', 'moda_atelier_registration_redirect' );

/**
 * Sanitize an international WhatsApp phone number to digits only.
 *
 * @param string $number Phone number, including country code.
 * @return string
 */
function moda_atelier_sanitize_whatsapp_number( $number ) {
	$digits = substr( preg_replace( '/\D+/', '', (string) $number ), 0, 15 );

	return strlen( $digits ) >= 8 ? $digits : '';
}

/**
 * Build the store's WhatsApp contact URL.
 *
 * @return string
 */
function moda_atelier_get_whatsapp_url() {
	$number = moda_atelier_sanitize_whatsapp_number(
		get_theme_mod( 'moda_atelier_whatsapp_number', '905061668911' )
	);

	if ( ! $number ) {
		return '';
	}

	return 'https://wa.me/' . $number . '?text=' . rawurlencode( __( 'Merhaba Moda Chicago, ürünler hakkında bilgi almak istiyorum.', 'moda-atelier' ) );
}

/**
 * Render an uploaded product video inside the WooCommerce product gallery.
 *
 * @return void
 */
function moda_atelier_render_product_video() {
	$product_id = get_the_ID();
	$video_id   = absint( get_post_meta( $product_id, '_moda_store_product_video_id', true ) );
	$mime_type  = $video_id ? get_post_mime_type( $video_id ) : '';
	$video_url  = $video_id ? wp_get_attachment_url( $video_id ) : '';
	if ( ! $video_url || ! in_array( $mime_type, array( 'video/mp4', 'video/webm' ), true ) ) {
		return;
	}

	$image_id  = get_post_thumbnail_id( $product_id );
	$poster    = $image_id ? wp_get_attachment_image_url( $image_id, 'woocommerce_single' ) : '';
	?>
	<div class="ma-product-video">
		<video controls playsinline preload="metadata"<?php echo $poster ? ' poster="' . esc_url( $poster ) . '"' : ''; ?>>
			<source src="<?php echo esc_url( $video_url ); ?>" type="<?php echo esc_attr( $mime_type ); ?>">
			<?php esc_html_e( 'Tarayıcınız bu ürün videosunu oynatamıyor.', 'moda-atelier' ); ?>
		</video>
		<p><?php esc_html_e( 'Ürün videosu', 'moda-atelier' ); ?></p>
	</div>
	<?php
}
add_action( 'woocommerce_product_thumbnails', 'moda_atelier_render_product_video', 20 );

