/**
 * Render a WooCommerce-driven product section.
 *
 * @param string $section_key Editable homepage section key.
 * @param array  $query Product query arguments.
 * @param string $anchor Section anchor.
 * @return void
 */
function moda_atelier_product_section( $section_key, $query, $anchor ) {
	if ( ! function_exists( 'wc_get_products' ) ) {
		return;
	}

	$section_defaults = array(
		'new_season' => array(
			'eyebrow' => __( 'Sizin için seçtiklerimiz', 'moda-atelier' ),
			'title'   => __( 'Yeni sezon', 'moda-atelier' ),
			'link'    => __( 'Yeni gelenleri gör', 'moda-atelier' ),
		),
		'best_sellers' => array(
			'eyebrow' => __( 'Sizin için seçtiklerimiz', 'moda-atelier' ),
			'title'   => __( 'Çok satanlar', 'moda-atelier' ),
			'link'    => __( 'Çok satanları gör', 'moda-atelier' ),
		),
		'sale' => array(
			'eyebrow' => __( 'Sizin için seçtiklerimiz', 'moda-atelier' ),
			'title'   => __( 'Sezon indirimi', 'moda-atelier' ),
			'link'    => __( 'İndirimli ürünleri gör', 'moda-atelier' ),
		),
	);
	if ( ! isset( $section_defaults[ $section_key ] ) ) {
		return;
	}

	$defaults = $section_defaults[ $section_key ];
	$products = wc_get_products( array_merge(
		array(
			'status'  => 'publish',
			'limit'   => 4,
			'return'  => 'objects',
		),
		$query
	) );
	?>
	<section class="ma-section" id="<?php echo esc_attr( $anchor ); ?>">
		<div class="ma-container">
			<div class="ma-section-heading">
				<div>
					<p class="ma-eyebrow"><?php echo esc_html( get_theme_mod( 'moda_atelier_' . $section_key . '_eyebrow', $defaults['eyebrow'] ) ); ?></p>
					<h2><?php echo esc_html( get_theme_mod( 'moda_atelier_' . $section_key . '_title', $defaults['title'] ) ); ?></h2>
				</div>
				<a class="ma-text-link" href="<?php echo esc_url( home_url( '/#' . $anchor ) ); ?>"><?php echo esc_html( get_theme_mod( 'moda_atelier_' . $section_key . '_link', $defaults['link'] ) ); ?></a>
			</div>
			<?php if ( $products ) : ?>
				<div class="ma-product-grid">
					<?php foreach ( $products as $product ) : ?>
						<?php moda_atelier_render_product_card( $product ); ?>
					<?php endforeach; ?>
				</div>
			<?php else : ?>
				<p class="ma-empty-state"><?php esc_html_e( 'WooCommerce üzerinden ürün eklendiğinde bu koleksiyon burada görüntülenir.', 'moda-atelier' ); ?></p>
			<?php endif; ?>
		</div>
	</section>
	<?php
}

/**
 * Keep every cart counter (header and mobile bar) current after AJAX add-to-cart.
 *
 * @param array<string,string> $fragments Cart fragments.
 * @return array<string,string>
 */
function moda_atelier_cart_count_fragment( $fragments ) {
	$count = function_exists( 'WC' ) && WC()->cart ? WC()->cart->get_cart_contents_count() : 0;

	$fragments['.ma-header-actions .ma-cart-count'] = '<span class="ma-cart-count">' . esc_html( (string) $count ) . '</span>';
	$fragments['.ma-bottom-nav .ma-cart-count']     = '<span class="ma-cart-count ma-bottom-nav-badge">' . esc_html( (string) $count ) . '</span>';

	return $fragments;
}
add_filter( 'woocommerce_add_to_cart_fragments', 'moda_atelier_cart_count_fragment' );

/**
 * Send conservative security headers.
 *
 * HSTS omits includeSubDomains and preload so mail and hosting subdomains are not affected.
 *
 * @return void
 */
function moda_atelier_security_headers() {
	if ( headers_sent() ) {
		return;
	}
	if ( is_ssl() ) {
		header( 'Strict-Transport-Security: max-age=15552000' );
	}
	header( 'X-Content-Type-Options: nosniff' );
	header( 'X-Frame-Options: SAMEORIGIN' );
	header( 'Referrer-Policy: strict-origin-when-cross-origin' );
	header( 'Permissions-Policy: camera=(), microphone=(), geolocation=()' );
}
add_action( 'send_headers', 'moda_atelier_security_headers' );

/**
 * Hide account names from anonymous visitors and disable XML-RPC.
 */
add_filter( 'xmlrpc_enabled', '__return_false' );

/**
 * Refuse every XML-RPC request, including unauthenticated method discovery.
 *
 * @return void
 */
function moda_atelier_block_xmlrpc() {
	if ( defined( 'XMLRPC_REQUEST' ) && XMLRPC_REQUEST ) {
		wp_die( esc_html__( 'XML-RPC kapalıdır.', 'moda-atelier' ), '', array( 'response' => 403 ) );
	}
}
add_action( 'init', 'moda_atelier_block_xmlrpc', 0 );

/**
 * Remove user listing routes for visitors who are not signed in.
 *
 * @param array $endpoints REST endpoints.
 * @return array
 */
function moda_atelier_hide_rest_users( $endpoints ) {
	if ( ! is_user_logged_in() ) {
		foreach ( array_keys( $endpoints ) as $route ) {
			if ( 0 === strpos( $route, '/wp/v2/users' ) ) {
				unset( $endpoints[ $route ] );
			}
		}
	}
	return $endpoints;
}
add_filter( 'rest_endpoints', 'moda_atelier_hide_rest_users' );

/**
 * Send author archives (which reveal usernames) to the home page.
 *
 * @return void
 */
function moda_atelier_redirect_author_archives() {
	if ( is_author() || ( isset( $_GET['author'] ) && ! is_admin() ) ) { // phpcs:ignore WordPress.Security.NonceVerification.Recommended
		wp_safe_redirect( home_url( '/' ), 301 );
		exit;
	}
}
add_action( 'template_redirect', 'moda_atelier_redirect_author_archives', 1 );
